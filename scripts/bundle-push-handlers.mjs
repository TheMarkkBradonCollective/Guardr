import * as esbuild from 'esbuild';

const routes = [
  { entry: 'api/_push/entries/vapid-public-key.ts', outfile: 'api/push/vapid-public-key.ts' },
  { entry: 'api/_push/entries/subscribe.ts', outfile: 'api/push/subscribe.ts' },
  { entry: 'api/_push/entries/unsubscribe.ts', outfile: 'api/push/unsubscribe.ts' },
  { entry: 'api/_push/entries/test.ts', outfile: 'api/push/test.ts' },
  { entry: 'api/_push/entries/events.ts', outfile: 'api/push/events.ts' },
  { entry: 'api/_push/entries/send.ts', outfile: 'api/push/send.ts' },
  { entry: 'api/_push/entries/missed-checkins.ts', outfile: 'api/cron/missed-checkins.ts' },
  { entry: 'api/_push/entries/company-placard-expiry.ts', outfile: 'api/cron/company-placard-expiry.ts' },
  { entry: 'api/_push/entries/pre-shift-briefings.ts', outfile: 'api/cron/pre-shift-briefings.ts' },
];

for (const route of routes) {
  await esbuild.build({
    entryPoints: [route.entry],
    bundle: true,
    platform: 'node',
    format: 'esm',
    outfile: route.outfile,
    packages: 'external',
    banner: {
      js: '// Generated by scripts/bundle-push-handlers.mjs — do not edit.\n// @ts-nocheck',
    },
  });
}

console.log('Bundled push API routes for Vercel:', routes.map((r) => r.outfile).join(', '));
